#!/usr/bin/env python3
"""
Generate CREDITS.md from the `credit` blocks in data/artifacts.js and
data/locations.js.

The data files are the single source of truth for image provenance, so
the credits page can never drift out of step with what the site shows.
Re-run this after adding or changing any entry:

    python3 scripts/make_credits.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def extract(path, var_name):
    """
    Pull one `const NAME = [ ... ];` array out of a .js file and parse it.

    The data files are written as valid JSON inside the array literal
    (double-quoted keys and strings), with one exception: long strings are
    joined with `+` across lines for readability. We stitch those back
    together first, then hand the result to json.loads.
    """
    with open(path, encoding="utf-8") as fh:
        source = fh.read()

    start = source.index("const " + var_name)
    start = source.index("[", start)

    # Walk forward tracking bracket depth, ignoring brackets inside strings.
    depth, i, in_string, escaped = 0, start, False, False
    while i < len(source):
        ch = source[i]
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
        else:
            if ch == '"':
                in_string = True
            elif ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    break
        i += 1

    literal = source[start:i + 1]

    # Strip // comments that sit on their own line. (A "//" inside a URL is
    # never at the start of a line, so this cannot touch string contents.)
    literal = re.sub(r"^\s*//.*$", "", literal, flags=re.MULTILINE)
    # Join "a" +\n"b" string concatenations back into one string. Doing this
    # before quoting keys means no string can still span multiple lines.
    literal = re.sub(r'"\s*\+\s*\n\s*"', "", literal)
    # Quote bare JavaScript keys (id: -> "id":). Anchored to the start of a
    # line, which only ever holds a key in these files -- continuation lines
    # of a string always begin with a quote character.
    literal = re.sub(r'^(\s*)([A-Za-z_][A-Za-z0-9_]*)(\s*):',
                     r'\1"\2"\3:', literal, flags=re.MULTILINE)
    # Remove trailing commas before a closing brace/bracket.
    literal = re.sub(r",(\s*[}\]])", r"\1", literal)

    return json.loads(literal)


def row(entry, name_key):
    c = entry["credit"]
    return (
        f"### {entry[name_key]}\n\n"
        f"- **Image file:** `{entry['image']}`\n"
        f"- **Title on Commons:** {c['title']}\n"
        f"- **Author / photographer:** {c['author']}\n"
        f"- **Licence:** {c['licence']}\n"
        f"- **Source:** <{c['source']}>\n\n"
    )


def main():
    artifacts = extract(os.path.join(HERE, "data", "artifacts.js"), "ARTIFACTS")
    locations = extract(os.path.join(HERE, "data", "locations.js"), "LOCATIONS")

    out = [
        "# Image Credits\n\n",
        "Every image used on this site was downloaded from "
        "[Wikimedia Commons](https://commons.wikimedia.org) and is either in the "
        "public domain or released under a Creative Commons licence. No other "
        "image sources were used, and no image URL was invented — each file was "
        "found by searching the Commons API and then verified.\n\n",
        "Images were downloaded at approximately 1200px wide using the Commons "
        "thumbnail renderer, so no local image processing was needed.\n\n",
        "Licence abbreviations: **CC0** public domain dedication; "
        "**CC BY** attribution; **CC BY-SA** attribution + share-alike; "
        "**Public domain** out of copyright.\n\n",
        "This file is generated by `scripts/make_credits.py` from the `credit` "
        "blocks in `data/artifacts.js` and `data/locations.js`. Edit those, not "
        "this file.\n\n",
        "---\n\n",
        f"## Timeline artifacts ({len(artifacts)})\n\n",
    ]
    for a in artifacts:
        out.append(row(a, "title"))

    out.append("---\n\n")
    out.append(f"## Map art forms ({len(locations)})\n\n")
    for l in locations:
        out.append(row(l, "name"))

    # A quick licence tally, useful as a sanity check.
    tally = {}
    for e in artifacts + locations:
        lic = e["credit"]["licence"]
        tally[lic] = tally.get(lic, 0) + 1

    out.append("---\n\n## Licence summary\n\n")
    out.append("| Licence | Number of images |\n|---|---|\n")
    for lic in sorted(tally):
        out.append(f"| {lic} | {tally[lic]} |\n")
    out.append(f"| **Total** | **{len(artifacts) + len(locations)}** |\n")

    dest = os.path.join(HERE, "CREDITS.md")
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("".join(out))

    print(f"wrote {dest}")
    print(f"  {len(artifacts)} artifacts + {len(locations)} locations")
    for lic in sorted(tally):
        print(f"  {tally[lic]:>2}  {lic}")


if __name__ == "__main__":
    main()
